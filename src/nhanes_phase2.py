def analyze_event_pair(df_in, col_A, col_B, name_A, name_B):
    N_tot = len(df_in)
    pA = df_in[col_A].mean()
    pB = df_in[col_B].mean()
    n_AB = int(((df_in[col_A] == 1) & (df_in[col_B] == 1)).sum())
    p_AB = n_AB / N_tot
    p_A_prod_B = pA * pB
    p_A_given_B = df_in.loc[df_in[col_B] == 1, col_A].mean()
    p_A_given_notB = df_in.loc[df_in[col_B] == 0, col_A].mean()
    p_B_given_A = df_in.loc[df_in[col_A] == 1, col_B].mean()
    p_B_given_notA = df_in.loc[df_in[col_A] == 0, col_B].mean()
    diff_indep = p_AB - p_A_prod_B
    rr = p_A_given_B / p_A_given_notB
    return {
        'name_A': name_A, 'name_B': name_B,
        'pA': pA, 'pB': pB, 'n_AB': n_AB, 'p_AB': p_AB,
        'p_A_prod_B': p_A_prod_B, 'diff_indep': diff_indep,
        'p_A_given_B': p_A_given_B, 'p_A_given_notB': p_A_given_notB,
        'p_B_given_A': p_B_given_A, 'p_B_given_notA': p_B_given_notA,
        'rr': rr
    }



pair_HO = analyze_event_pair(df_final, 'Event_H_HighBP', 'Event_O_Obese', 'High BP (H)', 'Obesity (O)')
